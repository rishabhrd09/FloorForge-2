function status(text) { $('view-status').textContent = text; }

// ---------------------------------------------------------------- boot
async function boot() {
  const packaged = window.__ELECTRICAL_TOUR_DATA__;
  const [scene, data] = packaged ? [packaged.scene, packaged.model]
    : await Promise.all([fetch('scene.json').then((r) => r.json()), fetch('electrical-model.json').then((r) => r.json())]);
  delete window.__ELECTRICAL_TOUR_DATA__;
  if (scene.planHash !== data.architecturalPlanHash) throw Error('The electrical model does not match this house.');
  const viewer = new window.FloorForgeViewer($('home-canvas'), { quality: 'auto', hudInset: 54, onStatus: () => {} });
  app.viewer = viewer;
  viewer.setScene(scene);
  viewer.setMode('dollhouse');
  viewer.setFloor(0);
  viewer.setFocus(true);
  app.model = new Model(data);
  // The model's defaults: lights on (as the architectural renders show them); fans,
  // exhaust fans, sockets and water heaters off.
  app.sim = new Simulation(data, createState(data));
  app.root = new THREE.Group();
  app.root.name = 'Electrical installation (simulation)';
  viewer.root.add(app.root);
  app.apertures = new Apertures(viewer);
  // an electrician's inspection lamp that follows the eye while a cover is off
  app.torch = new THREE.SpotLight('#fff4e2', 0, 2.6, .5, .6, 1.4);
  app.torch.castShadow = false;
  viewer.scene.add(app.torch, app.torch.target);
  app.labels = new LabelLayer(document.querySelector('.view3d'), viewer);
  app.routes = new RouteLayer(app);
  buildFittings(scene);
  clipOurMaterials();
  bindUI();
  renderSources(app.model);
  setMode('dollhouse');
  refresh();
  status('Choose a circuit, or use Walk inside and click a switchboard to open it.');
  setInterval(() => { app.labels.update(); }, 1000 / 30);
  requestAnimationFrame(loop);
  window.__electricalTour = api();
}

function buildFittings(scene) {
  const m = app.model;
  for (const e of m.data.enclosures) {
    let parts;
    if (['switchboard', 'socket-plate', 'geyser-mcb', 'geyser-outlet'].includes(e.kind)) {
      parts = buildPlate(m, e, app.pickables);
      // sight-line targets just in front of the plate (centre and a little above) for walk-mode culling
      const f = e.mount.face, n = e.mount.normal;
      parts.cull = [s2t([f[0] + n[0] * .04, f[1] + n[1] * .04, f[2]]), s2t([f[0] + n[0] * .04, f[1] + n[1] * .04, f[2] + .12])];
      parts.seen = true;
      app.cullList.push(parts);
    }
    else if (['main-db', 'sub-db', 'loose-wire-box'].includes(e.kind)) parts = buildDB(m, e, app.pickables);
    else if (e.kind === 'meter') { parts = buildMeter(m, e, app.pickables); app.meterLed = parts.led; }
    if (!parts) continue;
    parts.floor = e.floor;
    app.root.add(parts.group);
    app.parts.set(e.id, parts);
  }
  for (const p of m.data.points) {
    if (p.kind === 'fan') {
      const f = buildFan(m, p, m.get(p.boxId), app.pickables);
      f.floor = p.floor;
      f.speed = 0;
      // hub and two blade tips at the blade plane
      const [x, y] = p.position, zb = p.floor * H + 2.69, r = p.sweep / 2000 * .85;
      f.cull = [s2t([x, y, zb]), s2t([x + r, y, zb]), s2t([x - r, y, zb]), s2t([x, y + r, zb]), s2t([x, y - r, zb])];
      f.seen = true;
      app.cullList.push(f);
      app.root.add(f.group);
      app.fans.set(p.id, f);
    } else if (p.kind === 'exhaust') {
      const x = buildExhaust(m, p, app.pickables);
      x.floor = p.floor; x.speed = 0;
      app.root.add(x.group);
      app.exhausts.set(p.id, x);
      const box = m.get(p.boxId);
      const op = buildOutletPlate(m, box, app.pickables);
      op.floor = p.floor;
      app.root.add(op.group);
      app.parts.set(box.id, op);
    }
  }
  for (const b of m.data.boxes) if (b.kind === 'earth-pit') { const pit = buildPit(m, b, app.pickables); pit.floor = 0; app.root.add(pit.group); app.parts.set(b.id, pit); }
  app.caps = buildLightCaps(m, scene, m.data.points);
  app.root.add(app.caps.on, app.caps.off);
  scene.lights.forEach((l, i) => app.sceneLightColour.set(i, l.color || '#ffdfae'));
}

// Our physical materials share the architectural cutaway plane so nothing floats above a cut wall.
function clipOurMaterials() {
  const plane = app.viewer.materials.clipPlane;
  app.root.traverse((o) => {
    if (!o.isMesh) return;
    for (const m of Array.isArray(o.material) ? o.material : [o.material]) {
      if (!m.clippingPlanes) { m.clippingPlanes = [plane]; m.clipShadows = true; m.needsUpdate = true; }
    }
  });
}

// ---------------------------------------------------------------- state -> visuals
function refresh() {
  const { sim, model } = app;
  const snap = app.ui.snapshot = sim.snapshot();
  for (const [id, parts] of app.parts) {
    if (parts.rockers) for (const [sid, r] of parts.rockers) setRocker(r, sim.switchClosed(sid), Boolean(r.userData.mcb));
    if (parts.knobs) for (const [rid, k] of parts.knobs) k.rotation.z = -sim.regulatorStep(rid) * .52 + 1.3;
  }
  // light caps and the architectural light sources they stand for
  const zero = new THREE.Matrix4().makeScale(0, 0, 0);
  const lights = app.viewer.data.lights;
  for (const p of app.caps.downs) {
    const i = app.caps.index.get(p.id);
    const on = snap.points[p.id];
    const mtx = new THREE.Matrix4();
    (on ? app.caps.off : app.caps.on).setMatrixAt(i, zero);
    capMatrix(p, mtx);
    (on ? app.caps.on : app.caps.off).setMatrixAt(i, mtx);
    if (p.sceneLight != null) lights[p.sceneLight].color = on ? app.sceneLightColour.get(p.sceneLight) : '#000000';
  }
  for (const p of model.data.points) {
    if ((p.kind === 'mirror-light' || p.kind === 'undercabinet') && p.sceneLight != null) lights[p.sceneLight].color = snap.points[p.id] ? app.sceneLightColour.get(p.sceneLight) : '#000000';
  }
  app.caps.on.instanceMatrix.needsUpdate = app.caps.off.instanceMatrix.needsUpdate = true;
  app.viewer.updateLights(true);
  for (const [pid, f] of app.fans) {
    const reg = model.get(model.get(pid).regulator);
    f.target = snap.points[pid] ? (sim.regulatorStep(reg.id) / reg.steps) * 9 : 0;
  }
  for (const [pid, x] of app.exhausts) x.target = snap.points[pid] ? 30 : 0;
  // DB toggles when a board interior is open
  for (const d of model.data.devices) if (d._toggle) d._toggle.position.y = (sim.closed(d.id) ? .006 : -.004);
  renderCircuits(model, app.ui);
  renderControls(model, sim, { encId: app.ui.open?.id || selectedEnclosure(), circuitId: app.ui.circuitId });
  renderSupply(model, sim, app.ui.circuitId);
  renderPlan();
  updateInspector();
  app.viewer.dirty = true;
}

function capMatrix(p, out) {
  const r = p.lens.r + .0012;
  return out.compose(s2t([p.lens.xy[0], p.lens.xy[1], p.lens.bottom - .0006]), new THREE.Quaternion(), new THREE.Vector3(r, 1, r));
}

function selectedEnclosure() {
  const s = app.ui.selection && app.model.get(app.ui.selection.ref);
  if (!s) return null;
  if (s._type === 'enclosures') return s.id;
  if (s.enclosureId) return s.enclosureId;
  return null;
}

// ---------------------------------------------------------------- per-frame
let last = performance.now();
function loop(now) {
  const dt = Math.min(.05, (now - last) / 1000);
  last = now;
  const v = app.viewer;
  const walk = v.mode === 'walk';
  const floor = walk ? v.levelOf(v.walker.position.y) : v.floor;
  const storey = Math.max(0, Math.min(1, floor));
  if (walk && storey !== app.ui.floor) {
    // walking up or down the stairs (or a teleport) changes the floor shown in the toolbar and plan
    app.ui.floor = storey;
    for (const b of document.querySelectorAll('[data-floor]')) b.setAttribute('aria-pressed', String(Number(b.dataset.floor) === storey));
    renderPlan();
  }
  let busy = false;
  for (const [, f] of app.fans) {
    f.speed += (f.target - f.speed) * Math.min(1, dt * 1.2);
    if (Math.abs(f.speed) > .01 && f.group.visible) { f.rotor.rotation.y -= f.speed * dt; busy = true; }
  }
  for (const [, x] of app.exhausts) {
    x.speed += (x.target - x.speed) * Math.min(1, dt * 2);
    if (Math.abs(x.speed) > .01 && x.group.visible) { x.hub.rotation.z -= x.speed * dt; busy = true; }
  }
  if (app.meterLed) {
    const watts = loadWatts();
    const rate = watts / 1000;                 // blink rate grows with operating load (illustrative)
    app.meterLed.material.emissiveIntensity = watts > 0 && (now / 1000 * rate) % 1 < .12 ? 3 : 0;
  }
  // floor and mode visibility: hide fittings on floors above the cut so nothing floats; in walk
  // mode small flush plates behind walls are skipped (they cannot be seen and only cost draw calls)
  const cut = v.mode === 'dollhouse' || v.mode === 'plan';
  if (walk) cullFittings(!app.wasWalk);
  app.wasWalk = walk;
  const openId = app.ui.open?.id;
  for (const coll of [app.parts, app.fans, app.exhausts]) for (const [id, p] of coll) {
    p.group.visible = (!cut || p.floor <= floor) && (!walk || p.seen !== false || id === openId);
  }
  // the traced route is drawn on ceilings and upper walls, which the cutaway removes: use the plan there
  app.routes.group.visible = !cut;
  if (app.ui.circuitId && app.routes.group.children.length) {
    const live = app.ui.snapshot?.circuits?.[app.ui.circuitId];
    app.routes.flow(live ? now / 1000 : null);
    if (live) busy = true;
  }
  // animate an opening enclosure / fan canopy
  const op = app.ui.open;
  if (op && op.t !== op.goal) {
    const real = Math.min(.25, (now - (op.last || now)) / 1000);
    op.t += Math.sign(op.goal - op.t) * Math.min(Math.abs(op.goal - op.t), real / .9);
    op.handle.set(op.t);
    if (op.fan) op.fan.canopyGroup.position.y = -op.t * .16;
    busy = true;
    if (op.t === 0 && op.goal === 0) finishClose();
  }
  if (op) op.last = now;
  const inspecting = Boolean(app.ui.open || app.routes.cut);
  document.querySelector('.view3d').classList.toggle('inspecting', inspecting);
  // a softer lamp for the large white DB interior, which otherwise over-exposes and blooms
  const openKind = app.ui.open && app.model.get(app.ui.open.id)?.kind;
  app.torch.intensity = !inspecting ? 0 : openKind === 'main-db' || openKind === 'sub-db' ? .9 : 2.2;
  if (inspecting) {
    app.torch.position.copy(v.camera.position);
    const fwd = new THREE.Vector3(0, 0, -1).applyQuaternion(v.camera.quaternion);
    app.torch.target.position.copy(v.camera.position).addScaledVector(fwd, 1);
    app.torch.target.updateMatrixWorld();
  }
  if (busy) v.dirty = true;
  requestAnimationFrame(loop);
}

function loadWatts() {
  let w = 0;
  for (const p of app.model.data.points) if (app.ui.snapshot.points[p.id]) w += ({ fan: 60, socket6: 100, socket16: 1000, 'geyser-outlet': 1000, downlight: 8 })[p.kind] || 0;
  return w;
}

// ---------------------------------------------------------------- selection
// thin amber shell around the picked mesh (engineering overlay, not a physical part)
function highlight(mesh) {
  if (app.shell) { app.shell.parent?.remove(app.shell); app.shell.geometry.dispose(); app.shell = null; }
  if (!mesh?.geometry?.attributes?.normal) return;
  const g = mesh.geometry.clone();
  const pos = g.attributes.position, nor = g.attributes.normal;
  g.computeBoundingSphere();
  const grow = Math.min(.004, Math.max(.0007, g.boundingSphere.radius * .04));
  for (let i = 0; i < pos.count; i++) pos.setXYZ(i, pos.getX(i) + nor.getX(i) * grow, pos.getY(i) + nor.getY(i) * grow, pos.getZ(i) + nor.getZ(i) * grow);
  const shell = new THREE.Mesh(g, new THREE.MeshBasicMaterial({ color: '#f0a63a', side: THREE.BackSide, transparent: true, opacity: .95, depthWrite: false, toneMapped: false }));
  shell.renderOrder = 30;
  shell.userData = { overlay: true };
  mesh.add(shell);
  app.shell = shell;
  app.viewer.dirty = true;
}

function select(ref, anchor = null, { quiet = false, noLabel = false, mesh = null } = {}) {
  const m = app.model;
  const obj = ref ? m.get(ref) : null;
  app.ui.selection = obj ? { ref, anchor } : null;
  highlight(obj ? mesh : null);
  if (!obj) { app.labels.clearSelection(); updateInspector(); renderPlan(); return; }
  const cid = m.circuitOfObject(obj);
  if (cid && cid !== app.ui.circuitId && !app.ui.trace) setCircuit(cid, { quiet: true });
  const d = describe(m, app.sim, obj);
  const where = anchor || anchorOf(obj);
  if (where && app.ui.labels && !noLabel) app.labels.select(where, d.title, d.rows.slice(0, 6));
  else app.labels.clearSelection();
  updateInspector();
  renderPlan();
  if (!quiet) status(`${d.type}: ${d.title}`);
}

function anchorOf(obj) {
  const m = app.model;
  if (obj._type === 'enclosures') return s2t(obj.mount.face);
  if (obj._type === 'points') return s2t(obj.position);
  if (obj._type === 'boxes') return s2t(obj.mount ? obj.mount.face : obj.position);
  if (obj._type === 'terminals') return m.terminalWorld(obj.id);
  if (obj._type === 'devices' && obj.enclosureId) { const e = m.get(obj.enclosureId); return m.local(e, [obj.x ?? 0, obj.y ?? 0, -.01]); }
  if (obj._type === 'conduits') { const p = obj.reveal?.[0]; return p ? s2t(p.a).lerp(s2t(p.b), .5) : s2t(obj.points[Math.floor(obj.points.length / 2)]); }
  if (obj._type === 'conductors') { const t = m.terminalWorld(obj.to); return t; }
  return null;
}

function updateInspector() {
  const sel = app.ui.selection && app.model.get(app.ui.selection.ref);
  const obj = sel || (app.ui.circuitId ? app.model.circuit(app.ui.circuitId) : null);
  let actions = '';
  if (obj?._type === 'enclosures' && obj.kind !== 'meter') actions += `<button class="primary" data-act="open" data-ref="${esc(obj.id)}">${app.ui.open?.id === obj.id || app.ui.open?.id === obj.db ? 'Close cover' : 'Open cover'}</button>`;
  if (obj?._type === 'points' && (obj.kind === 'fan' || obj.kind === 'downlight')) actions += `<button class="primary" data-act="openpoint" data-ref="${esc(obj.id)}">${app.ui.open?.id === obj.boxId ? 'Close' : obj.kind === 'fan' ? 'Lower the canopy' : 'Inspect point box'}</button>`;
  const cid = obj && app.model.circuitOfObject(obj);
  if (cid && !app.ui.trace) actions += `<button class="tool" data-act="trace" data-ref="${esc(cid)}">Follow ${esc(cid)} from the meter</button>`;
  renderInspector(app.model, app.sim, obj, actions);
}

function setCircuit(cid, { quiet = false } = {}) {
  app.ui.circuitId = cid;
  app.ui.planView = null;
  app.routes.show(cid);
  renderCircuits(app.model, app.ui);
  renderControls(app.model, app.sim, { encId: app.ui.open?.id || selectedEnclosure(), circuitId: cid });
  renderSupply(app.model, app.sim, cid);
  renderPlan();
  if (!app.ui.selection) updateInspector();
  if (!quiet && cid) status(`${app.model.circuit(cid).label}. Cyan marks its concealed route on ceilings and walls; walls still hide other rooms.`);
}

// ---------------------------------------------------------------- picking
const ray = new THREE.Raycaster();
function pick(clientX, clientY) {
  const canvas = $('home-canvas');
  const r = canvas.getBoundingClientRect();
  const ndc = new THREE.Vector2((clientX - r.left) / r.width * 2 - 1, -(clientY - r.top) / r.height * 2 + 1);
  ray.setFromCamera(ndc, app.viewer.camera);
  const visible = (o) => { for (let p = o; p; p = p.parent) if (!p.visible) return o.userData?.proxy; return true; };
  const hits = ray.intersectObjects(app.pickables.filter(visible), false);
  if (!hits.length) return null;
  const v = app.viewer;
  const clipY = (v.mode === 'dollhouse' || v.mode === 'plan') ? v.floor * H + 1.22 : Infinity;
  const arch = ray.intersectObjects(v.meshes.filter((x) => x.visible), false).find((h) => h.point.y < clipY && !inAperture(h.point));
  for (const h of hits) {
    if (h.point.y > clipY + .001) continue;
    if (arch && arch.distance < h.distance - .015 && !h.object.userData?.overlay) return null;
    return h;
  }
  return null;
}

function inAperture(p) {
  const b = app.apertures.box;
  if (!b) return false;
  const d = p.clone().sub(b.centre);
  return b.axes.every((ax, i) => Math.abs(d.dot(ax)) <= b.half[i] + .003);
}

function onClick(e) {
  const hit = pick(e.clientX, e.clientY);
  if (!hit) return;
  const u = hit.object.userData;
  const m = app.model;
  switch (u.kind) {
    case 'switch': {
      app.sim.toggleSwitch(u.ref);
      const sw = m.get(u.ref);
      refresh();
      select(sw.deviceId, hit.point, { quiet: true });
      const pts = sw.points.map((p) => m.get(p));
      status(`${sw.label}: ${app.sim.switchClosed(u.ref) ? 'ON' : 'OFF'} — only ${pts.length > 1 ? `these ${pts.length} points change` : 'this point changes'}; its neutral is untouched.`);
      return;
    }
    case 'regulator': {
      const reg = m.get(u.ref);
      app.sim.setRegulator(u.ref, (app.sim.regulatorStep(u.ref) + 1) % (reg.steps + 1));
      refresh();
      select(reg.deviceId, hit.point, { quiet: true });
      status(`Regulator step ${app.sim.regulatorStep(u.ref)} of ${reg.steps}.`);
      return;
    }
    case 'plate': case 'enclosure': {
      const enc = m.get(u.ref);
      if (enc?.kind === 'meter') { select(enc.id, hit.point); return; }
      // a closed board opens; parts of the board that is already open are identified instead
      const openId = app.ui.open?.id;
      const isOpen = Boolean(openId) && [enc.id, enc.lwb, enc.db].includes(openId);
      if (u.door || !isOpen) { openEnclosure(enc.id); return; }
      select(enc.id, hit.point);
      return;
    }
    case 'device': {
      const d = m.get(u.ref);
      if (u.toggle && d.operable) { app.sim.toggleDevice(d.id); refresh(); status(`${d.label}: ${app.sim.closed(d.id) ? 'closed (ON)' : 'open (OFF)'}.`); }
      select(u.ref, hit.point, { mesh: hit.object });
      return;
    }
    case 'fan-canopy': openPoint(u.ref); return;
    case 'trace': select(u.ref, hit.point); return;
    case 'fan-lead': select(u.ref, hit.point); status("Fan supply leads (manufacturer side). The fan's internal motor wiring is deliberately not shown."); return;
    default:
      if (u.ref) select(u.ref, hit.point, { mesh: hit.object });
  }
}

// ---------------------------------------------------------------- opening enclosures and points
function openEnclosure(id, { teleport = true } = {}) {
  const m = app.model;
  let enc = m.get(id);
  if (enc.kind === 'loose-wire-box') enc = m.get(enc.db);
  if (app.ui.open?.id === enc.id) { closeOpen(); return; }
  closeOpen(true);
  if (app.viewer.mode !== 'walk') setMode('walk');
  if (teleport) standInFront(enc);
  const parts = app.parts.get(enc.id);
  let handle, box;
  if (enc.kind === 'main-db' || enc.kind === 'sub-db') {
    const lwb = m.get(enc.lwb);
    handle = openDB(app, enc, parts, lwb, app.parts.get(lwb.id));
    const total = enc.size.h + lwb.size.h;
    const centreShift = lwb.size.h / 2;
    box = enclosureOpening(parts.group, enc.size.w, total, enc.size.depth);
    box.centre.addScaledVector(box.axes[1], centreShift);
  } else {
    handle = openModularBox(app, enc, parts);
    box = enclosureOpening(parts.group, enc.size.boxW, enc.size.boxH, enc.size.depth);
  }
  parts.group.updateMatrixWorld(true);
  app.apertures.open(box);
  clipOurMaterials();
  app.ui.open = { id: enc.id, handle, t: 0, goal: 1 };
  showCallouts(handle);
  select(enc.id, null, { quiet: true, noLabel: true });
  if (enc.circuitIds?.[0] && !app.ui.trace) setCircuit(enc.circuitIds[0], { quiet: true });
  renderControls(m, app.sim, { encId: enc.id, circuitId: app.ui.circuitId });
  status(`${enc.label} opened (de-energised in reality). Numbered callouts name the parts; click any wire, terminal or device.`);
}

function openPoint(pid) {
  const m = app.model;
  const p = m.get(pid);
  const box = p && m.get(p.boxId);
  if (!box) return;
  if (app.ui.open?.id === box.id) { closeOpen(); return; }
  closeOpen(true);
  if (app.viewer.mode !== 'walk') setMode('walk');
  standBelow(p);
  const handle = openSlabBox(app, box);
  const fr = m.frame(box);
  const centre = new THREE.Vector3().setFromMatrixPosition(fr);
  const axes = [new THREE.Vector3(1, 0, 0), new THREE.Vector3(0, 0, 1), new THREE.Vector3(0, 1, 0)];
  const half = [box.size[0] / 2 + .012, box.size[1] / 2 + .012, (box.size[2] + .01) / 2];
  centre.y += (box.size[2] - .006) / 2;
  app.apertures.open({ centre, axes, half });
  clipOurMaterials();
  app.ui.open = { id: box.id, handle, t: 0, goal: 1, fan: p.kind === 'fan' ? app.fans.get(pid) : null };
  showCallouts(handle);
  select(pid, null, { quiet: true });
  status(p.kind === 'fan' ? 'Canopy lowered: fan box with hook, insulator and the house-wiring connector. Click a conductor to identify it.' : 'Point box opened above the light fitting.');
}

function showCallouts(handle) {
  const items = handle.callouts.filter((c) => c.ref || c.text).map((c, i) => ({ n: i + 1, anchor: handle.anchor(c), text: c.text, ref: c.ref, c }));
  app.ui.callouts = items;
  if (app.ui.labels) app.labels.setCallouts(items, { onPick: (ref) => select(ref) });
}

function closeOpen(immediate = false) {
  const op = app.ui.open;
  if (!op) return;
  if (immediate) { op.handle.set(0); if (op.fan) op.fan.canopyGroup.position.y = 0; op.t = 0; op.goal = 0; finishClose(); return; }
  op.goal = 0;
  const item = app.model.get(op.id);
  status(`${item?.label || 'Cover'}: ${op.fan ? 'canopy raised' : 'cover closing'}. Click it again to reopen.`);
}

function finishClose() {
  const op = app.ui.open;
  if (!op) return;
  op.handle.dispose();
  app.apertures.close();
  app.labels.clearCallouts();
  app.ui.callouts = null;
  app.ui.open = null;
  // drop pickables that belonged to the interior
  const alive = new Set();
  app.root.traverse((o) => alive.add(o));
  app.pickables.splice(0, app.pickables.length, ...app.pickables.filter((p) => alive.has(p) || p.userData?.overlay));
  updateInspector();
}

